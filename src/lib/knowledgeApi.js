const LOCAL_STORAGE_KEY = 'gsl_knowledge_articles';

/**
 * Get all knowledge articles
 */
export async function getKnowledgeArticles() {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Error reading knowledge articles from localStorage:', err);
  }
  // Initialize with default preset if none exists
  localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(DEFAULT_KNOWLEDGE_ITEMS));
  return DEFAULT_KNOWLEDGE_ITEMS;
}

/**
 * Save all knowledge articles
 */
export async function saveKnowledgeArticles(articles) {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(articles));
    window.dispatchEvent(new Event('knowledgeArticlesUpdated'));
    return articles;
  } catch (err) {
    console.error('Error saving knowledge articles:', err);
    throw err;
  }
}

/**
 * Create or add a new knowledge article
 */
export async function createKnowledgeArticle(articleData) {
  const articles = await getKnowledgeArticles();
  const newArticle = {
    ...articleData,
    id: articleData.id || `gsl_${Date.now()}`,
    updated_at: new Date().toISOString(),
  };
  const updated = [newArticle, ...articles];
  await saveKnowledgeArticles(updated);
  return newArticle;
}

/**
 * Update an existing article
 */
export async function updateKnowledgeArticle(id, updatedData) {
  const articles = await getKnowledgeArticles();
  const index = articles.findIndex(a => a.id === id);
  if (index === -1) {
    throw new Error('ไม่พบข้อมูลองค์ความรู้ที่ต้องการแก้ไข');
  }
  articles[index] = {
    ...articles[index],
    ...updatedData,
    updated_at: new Date().toISOString(),
  };
  await saveKnowledgeArticles(articles);
  return articles[index];
}

/**
 * Delete an article
 */
export async function deleteKnowledgeArticle(id) {
  const articles = await getKnowledgeArticles();
  const filtered = articles.filter(a => a.id !== id);
  await saveKnowledgeArticles(filtered);
  return true;
}

/**
 * Reset knowledge articles to system default
 */
export async function resetKnowledgeToDefault() {
  await saveKnowledgeArticles(DEFAULT_KNOWLEDGE_ITEMS);
  return DEFAULT_KNOWLEDGE_ITEMS;
}
